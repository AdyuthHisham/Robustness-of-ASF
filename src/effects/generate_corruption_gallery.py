#!/usr/bin/env python3
"""
Frame-level corruption visual comparison gallery.

For one representative K-Radar frame, applies all 22 corruption conditions
from amscup_paths import KRADAR_ROOT  # noqa: E402
from the robustness sweep's canonical taxonomy (original + 3 modalities x
{gaussian_noise, loss_partial} x {low, medium, high} + 3 modalities x
loss_complete_zero) and renders one image per (condition x modality), then
emits a single markdown gallery grouping by modality.

frame_deletion is intentionally excluded (drops whole frames, not a
per-frame content change -- not meaningful in a static single-frame
comparison; see the task spec this script was written against).

Read-only / inference-time only: loads raw sensor files directly (rdr_sparse
.npy, LiDAR .pcd, camera .png) and calls the standalone per-effect functions
in noise_injection.py on a minimal dict_item -- no K-Radar Dataset object,
no ASF model, no dataloader. Reuses the loaders and BEV/camera renderers
from visualize_effects_v2.py verbatim (same conventions: render_bev,
render_bev_zeroout for loss_partial's zero-out-aware BEV, tensor_to_bgr for
camera) rather than reimplementing them.

Severity parameters are read directly from the canonical single-effect
sweep configs at configs/noise/single/*.yml (generated by
scripts/alvis/gen_single_effect_configs.py) -- these are the exact values
used to produce the mAP robustness sweep, not re-derived approximations.

Run: .venv/bin/python datasets/effects/generate_corruption_gallery.py
     [--seq 46] [--rdr-idx 205] [--ldr-idx 200] [--cam-idx 585] [--label seq046_rdr205]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import cv2
import numpy as np
import torch
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import copy

from visualize_effects_v2 import (
    load_rdr_sparse, load_lidar_pcd, load_camera_img,
    make_dict_item,
    render_bev, render_bev_zeroout,
    tensor_to_bgr,
)
from noise_injection import (
    radar_gaussian_noise, radar_loss_partial, radar_loss_complete_zero,
    lidar_gaussian_noise, lidar_loss_partial, lidar_loss_complete_zero,
    camera_gaussian_noise, camera_loss_partial, camera_loss_complete_zero,
)

REPO_DIR = KRADAR_ROOT
CONFIG_DIR = REPO_DIR / "configs" / "noise" / "single"
OUTPUT_FIGURES_DIR = REPO_DIR / "figures" / "corruption_gallery"
OUTPUT_MD_PATH = REPO_DIR / "docs" / "corruption_visual_gallery.md"
SCRIPT_PATH = REPO_DIR / "datasets" / "effects" / "generate_corruption_gallery.py"

MASTER_SEED = 42

FN_MAP = {
    "radar": {
        "gaussian_noise": radar_gaussian_noise,
        "loss_partial": radar_loss_partial,
        "loss_complete_zero": radar_loss_complete_zero,
    },
    "lidar": {
        "gaussian_noise": lidar_gaussian_noise,
        "loss_partial": lidar_loss_partial,
        "loss_complete_zero": lidar_loss_complete_zero,
    },
    "camera": {
        "gaussian_noise": camera_gaussian_noise,
        "loss_partial": camera_loss_partial,
        "loss_complete_zero": camera_loss_complete_zero,
    },
}

SEVERITIES = ["low", "medium", "high"]
SEVERITY_EFFECTS = ["gaussian_noise", "loss_partial"]

# One-line descriptions, per docs/vAIlt/04_Design/Noise_Taxonomy.md and
# gen_single_effect_configs.py's per-effect notes.
EFFECT_DESCRIPTIONS = {
    "radar": {
        "gaussian_noise": "Isotropic additive N(0, sigma) noise on point xyz, independent of power/RCS/range.",
        "loss_partial": "Fraction of radar detections zeroed in place; row count preserved.",
        "loss_complete_zero": "Radar sensor alive but every reading zero-filled (not None) -- a present, well-formed all-zero frame.",
    },
    "lidar": {
        "gaussian_noise": "Isotropic additive N(0, sigma) noise on point xyz; severities matched to radar's.",
        "loss_partial": "Fraction of LiDAR points zeroed in place; row count preserved.",
        "loss_complete_zero": "LiDAR sensor alive but every reading zero-filled (not None) -- a present, well-formed all-zero frame.",
    },
    "camera": {
        "gaussian_noise": "Additive N(0, sigma) noise per pixel per channel, in 0-255 image units.",
        "loss_partial": "Fraction of individual scalar pixel values (R/G/B independently) zeroed out.",
        "loss_complete_zero": "Full image blackout (zero-filled normalized tensor).",
    },
}

# Perceptual-diff no-op detection thresholds.
POINTCLOUD_NOOP_FRAC = 0.005   # <0.5% of rows changed -> flag as possible no-op
CAMERA_NOOP_MEAN_ABS_DIFF = 1.0  # mean |delta| in 0-255 units


def apply_effect(dict_item: dict, modality: str, effect_name: str, params: dict, rng: np.random.Generator) -> dict:
    d = copy.deepcopy(dict_item)
    fn = FN_MAP[modality][effect_name]
    return fn(d, params, rng)


def _load_severity_params(modality: str, effect: str, severity: str) -> dict:
    path = CONFIG_DIR / f"{modality}_{effect}_{severity}.yml"
    with open(path) as f:
        raw = yaml.safe_load(f)
    entries = raw.get(modality, [])
    assert len(entries) == 1, f"expected exactly one effect in {path}, got {entries}"
    return entries[0].get("params", {}) or {}


def _seed_offset(modality: str, effect_name: str, severity: str) -> int:
    import hashlib
    h = hashlib.sha256(f"{modality}:{effect_name}:{severity}".encode()).digest()
    return int.from_bytes(h[:4], "little") % (2 ** 16)


def _pointcloud_noop_frac(clean: np.ndarray, corrupted: np.ndarray) -> float:
    if clean is None or corrupted is None or len(clean) == 0:
        return 0.0
    n = min(len(clean), len(corrupted))
    diff = ~np.all(np.isclose(clean[:n], corrupted[:n], atol=1e-6), axis=1)
    return float(diff.sum()) / n if n else 0.0


def _camera_noop_diff(clean_bgr: np.ndarray, corrupted_bgr: np.ndarray) -> float:
    return float(np.abs(clean_bgr.astype(np.float32) - corrupted_bgr.astype(np.float32)).mean())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seq", type=int, default=46)
    ap.add_argument("--rdr-idx", type=int, default=205)
    ap.add_argument("--ldr-idx", type=int, default=200)
    ap.add_argument("--cam-idx", type=int, default=585)
    ap.add_argument("--label", type=str, default="seq046_rdr205")
    args = ap.parse_args()

    seq, rdr_idx, ldr_idx, cam_idx, label = args.seq, args.rdr_idx, args.ldr_idx, args.cam_idx, args.label

    print(f"[LOAD] seq={seq} rdr={rdr_idx} ldr={ldr_idx} cam={cam_idx} label={label}")
    rdr = load_rdr_sparse(seq, rdr_idx)
    lidar = load_lidar_pcd(seq, ldr_idx)
    cam = load_camera_img(seq, cam_idx)
    print(f"  radar: {len(rdr)} pts  lidar: {len(lidar)} pts  cam: {cam.shape}")

    def _lims(arr, pad=3):
        return [float(arr[:, 0].min()) - pad, float(arr[:, 0].max()) + pad,
                float(arr[:, 1].min()) - pad, float(arr[:, 1].max()) + pad]

    ax_limits = {"radar": _lims(rdr, pad=3), "lidar": _lims(lidar, pad=3), "camera": None}

    idx = {"rdr": rdr_idx, "ldr": ldr_idx, "cam": cam_idx}
    clean_item = make_dict_item(rdr, lidar, cam, idx)

    OUTPUT_FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    OUTPUT_MD_PATH.parent.mkdir(parents=True, exist_ok=True)

    # noop/broken flags collected per (modality, condition)
    flags: list[tuple[str, str, str]] = []  # (modality, condition, note)
    rendered: dict[str, list[str]] = {"radar": [], "lidar": [], "camera": []}  # modality -> [condition names, in display order]

    def _render_pointcloud(modality: str, condition: str, data: np.ndarray | None,
                            clean_data: np.ndarray, title: str, zero_aware: bool) -> Path:
        fname = f"{modality}_{condition}.png" if condition == "original" else f"{condition}.png"
        out_path = OUTPUT_FIGURES_DIR / fname
        pts_data = data[:, :2] if data is not None and len(data) > 0 else None
        if zero_aware:
            is_zeroed = np.all(data == 0, axis=1) if data is not None else np.zeros(0, dtype=bool)
            render_bev_zeroout(pts_data, is_zeroed, ax_limits[modality], title, out_path)
        else:
            vals = (data[:, 3] if modality == "radar" and data is not None
                    and len(data) > 0 and data.shape[1] >= 4 else None)
            render_bev(pts_data, vals, ax_limits[modality], title, out_path)
        return out_path

    # ── original (clean) reference, once per modality ──
    for modality in ["radar", "lidar", "camera"]:
        condition = "original"
        title = f"original | {label}"
        if modality == "camera":
            out_path = OUTPUT_FIGURES_DIR / f"{modality}_{condition}.png"
            bgr = cam.copy()
            cv2.putText(bgr, title, (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (0, 255, 0), 2)
            cv2.imwrite(str(out_path), bgr)
        else:
            clean_data = clean_item["rdr_sparse" if modality == "radar" else "ldr64"]
            n_pts = len(clean_data)
            _render_pointcloud(modality, condition, clean_data, clean_data,
                                f"{title}\n{n_pts} pts", zero_aware=False)
        rendered[modality].append(condition)
        print(f"  [OK] {modality}/original")

    # ── severity-capable effects: gaussian_noise, loss_partial ──
    for modality in ["radar", "lidar", "camera"]:
        for eff_name in SEVERITY_EFFECTS:
            for severity in SEVERITIES:
                params = _load_severity_params(modality, eff_name, severity)
                condition = f"{modality}_{eff_name}_{severity}"
                seed_off = _seed_offset(modality, eff_name, severity)
                rng = np.random.default_rng(MASTER_SEED + seed_off)
                torch.manual_seed(MASTER_SEED + seed_off)

                corrupted = apply_effect(clean_item, modality, eff_name, params, rng)
                param_str = ", ".join(f"{k}={v}" for k, v in params.items())
                title = f"{eff_name} [{severity}] ({param_str}) | {label}"

                if modality == "camera":
                    tensor = corrupted.get("front0", None)
                    bgr = tensor_to_bgr(tensor) if tensor is not None else np.zeros((256, 704, 3), dtype=np.uint8)
                    out_path = OUTPUT_FIGURES_DIR / f"{modality}_{eff_name}_{severity}.png"
                    cv2.putText(bgr, title, (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (0, 255, 0), 2)
                    cv2.imwrite(str(out_path), bgr)
                    diff = _camera_noop_diff(cam, bgr)
                    if diff < CAMERA_NOOP_MEAN_ABS_DIFF:
                        flags.append((modality, condition, f"possible no-op: mean |pixel delta| = {diff:.3f}"))
                else:
                    key = "rdr_sparse" if modality == "radar" else "ldr64"
                    data = corrupted.get(key, None)
                    clean_data = clean_item[key]
                    n_pts = len(data) if data is not None else 0
                    is_new_style = eff_name == "loss_partial"
                    _render_pointcloud(modality, condition, data, clean_data,
                                        title + f"\n{n_pts} pts", zero_aware=is_new_style)
                    frac_changed = _pointcloud_noop_frac(clean_data, data)
                    if frac_changed < POINTCLOUD_NOOP_FRAC:
                        flags.append((modality, condition,
                                      f"possible no-op: only {frac_changed*100:.3f}% of rows changed"))

                rendered[modality].append(condition)
                print(f"  [OK] {modality}/{eff_name}/{severity}")

    # ── loss_complete_zero: single render, no severity axis ──
    for modality in ["radar", "lidar", "camera"]:
        eff_name = "loss_complete_zero"
        condition = f"{modality}_loss_complete_zero"
        seed_off = _seed_offset(modality, eff_name, "n_a")
        rng = np.random.default_rng(MASTER_SEED + seed_off)
        torch.manual_seed(MASTER_SEED + seed_off)

        corrupted = apply_effect(clean_item, modality, eff_name, {}, rng)
        title = f"loss_complete_zero | {label}"

        if modality == "camera":
            tensor = corrupted.get("front0", None)
            bgr = tensor_to_bgr(tensor) if tensor is not None else np.zeros((256, 704, 3), dtype=np.uint8)
            out_path = OUTPUT_FIGURES_DIR / f"{condition}.png"
            cv2.putText(bgr, title, (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (0, 255, 0), 2)
            cv2.imwrite(str(out_path), bgr)
        else:
            key = "rdr_sparse" if modality == "radar" else "ldr64"
            data = corrupted.get(key, None)
            clean_data = clean_item[key]
            n_pts = len(data) if data is not None else 0
            _render_pointcloud(modality, condition, data, clean_data,
                                title + f"\n{n_pts} pts", zero_aware=False)

        rendered[modality].append(condition)
        print(f"  [OK] {modality}/loss_complete_zero")

    print(f"\n[SUMMARY] {sum(len(v) for v in rendered.values())} images rendered")
    if flags:
        print(f"[FLAGS] {len(flags)} conditions flagged as possible no-op:")
        for mod, cond, note in flags:
            print(f"    {mod}/{cond}: {note}")

    # ── config used, for the report ──
    used_config_path = OUTPUT_FIGURES_DIR.parent / "corruption_gallery_config.yaml"
    with open(used_config_path, "w") as f:
        f.write(f"# Severity parameters actually applied -- read from {CONFIG_DIR}\n")
        f.write(f"seed: {MASTER_SEED}\n")
        f.write(f"frame: {{seq: {seq}, rdr_idx: {rdr_idx}, ldr_idx: {ldr_idx}, cam_idx: {cam_idx}, label: {label}}}\n\n")
        for modality in ["radar", "lidar", "camera"]:
            f.write(f"{modality}:\n")
            for eff_name in SEVERITY_EFFECTS:
                f.write(f"  {eff_name}:\n")
                for severity in SEVERITIES:
                    params = _load_severity_params(modality, eff_name, severity)
                    f.write(f"    {severity}: {params}\n")
            f.write("  loss_complete_zero: {}\n")

    _write_markdown(rendered, flags, label, seq, rdr_idx, ldr_idx, cam_idx)
    print(f"[DONE] Gallery markdown: {OUTPUT_MD_PATH}")


def _write_markdown(rendered: dict[str, list[str]], flags: list[tuple[str, str, str]],
                     label: str, seq: int, rdr_idx: int, ldr_idx: int, cam_idx: int) -> None:
    fig_rel = "../figures/corruption_gallery"  # relative from docs/ to figures/
    lines: list[str] = []
    lines.append("# Corruption Visual Gallery")
    lines.append("")
    lines.append(f"Frame: `{label}` (seq={seq}, rdr_idx={rdr_idx}, ldr_idx={ldr_idx}, cam_idx={cam_idx}), "
                  f"seed={MASTER_SEED}.")
    lines.append("")
    lines.append("Qualitative sanity check: does each corruption condition visually look like what its "
                  "name claims? Not a metrics report -- see `outputs/alvis_smoke/RESULTS.md` and "
                  "`obsidianVault/Projects/K-Radar/robustness-metrics-tables.md` for the quantitative "
                  "mAP sweep this taxonomy comes from.")
    lines.append("")
    lines.append("`frame_deletion` conditions are excluded -- they drop whole frames rather than "
                  "altering per-frame content, so a static single-frame comparison isn't meaningful "
                  "for them.")
    lines.append("")

    if flags:
        lines.append("## Flagged conditions (possible no-op or broken render)")
        lines.append("")
        for mod, cond, note in flags:
            lines.append(f"- **{mod}/{cond}**: {note}")
        lines.append("")
    else:
        lines.append("## Flagged conditions")
        lines.append("")
        lines.append("None -- every corrupted image differs perceptibly from `original`.")
        lines.append("")

    for modality in ["radar", "lidar", "camera"]:
        lines.append(f"## {modality.upper()}")
        lines.append("")

        # original
        lines.append("### Original")
        lines.append("")
        lines.append(f"![{modality} original]({fig_rel}/{modality}_original.png)")
        lines.append("")

        for eff_name in SEVERITY_EFFECTS:
            desc = EFFECT_DESCRIPTIONS[modality][eff_name]
            lines.append(f"### {eff_name.replace('_', ' ').title()}")
            lines.append("")
            lines.append(desc)
            lines.append("")
            lines.append("| Low | Medium | High |")
            lines.append("|---|---|---|")
            cells = []
            for severity in SEVERITIES:
                condition = f"{modality}_{eff_name}_{severity}"
                flagged = any(m == modality and c == condition for m, c, _ in flags)
                badge = " ⚠️ possible no-op" if flagged else ""
                cells.append(f"![{condition}]({fig_rel}/{condition}.png){badge}")
            lines.append("| " + " | ".join(cells) + " |")
            lines.append("")

        desc = EFFECT_DESCRIPTIONS[modality]["loss_complete_zero"]
        condition = f"{modality}_loss_complete_zero"
        flagged = any(m == modality and c == condition for m, c, _ in flags)
        badge = " ⚠️ possible no-op" if flagged else ""
        lines.append("### Loss Complete Zero")
        lines.append("")
        lines.append(desc)
        lines.append("")
        lines.append(f"![{condition}]({fig_rel}/{condition}.png){badge}")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(f"Generated by `datasets/effects/generate_corruption_gallery.py`. "
                  f"Severity parameters: `figures/corruption_gallery_config.yaml` "
                  f"(sourced from `configs/noise/single/*.yml`).")
    lines.append("")

    with open(OUTPUT_MD_PATH, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
